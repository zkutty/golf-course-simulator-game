import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const dist = new URL("../dist/", import.meta.url);
const worker = new URL("../dist/sw.js", import.meta.url);
const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const files = [];
function walk(directory) {
  for (const name of readdirSync(directory)) {
    if (name.startsWith(".") || name === "vite.svg") continue;
    const path = join(directory, name);
    if (statSync(path).isDirectory()) walk(path);
    else {
      const url = relative(dist.pathname, path).split(sep).join("/");
      if (url !== "sw.js" && !url.startsWith("audio/")) files.push(url);
    }
  }
}
walk(dist.pathname);
const source = readFileSync(worker, "utf8");
writeFileSync(worker, source
  .replace("__APP_VERSION__", pkg.version)
  .replace("const PRECACHE = []; // __COURSECRAFT_PRECACHE__", `const PRECACHE = ${JSON.stringify(files)}.map(scoped); // generated by inject-sw-assets.mjs`));
console.log(`Injected ${files.length} offline assets into dist/sw.js`);
